from ultralytics import YOLO
import torch

torch.cuda.empty_cache() if torch.cuda.is_available() else None
def main():


    model = YOLO('yolov8n.pt') 
    
    # Запуск обучения с добавлением параметров аугментации
    model.train(
        data='./dataset/data.yaml',
        epochs=100,      # Увеличиваем эпохи, чтобы модель лучше выучила Geely Atlas
        imgsz=640,
        batch=8,         # Максимально возможный для вашей памяти
        workers=4,       # 2-4 × количество CPU ядер
        device=0,
        lr0=0.01,
        
        # --- Параметры агрессивной аугментации (ДОБАВЛЕНО) ---
        
        # Аугментации цвета (HSV): помогает не привязываться к цвету конкретного автомобиля
        hsv_h=0.015,     # Оттенок (Hue) – стандартное значение
        hsv_s=0.7,       # Насыщенность (Saturation) – УВЕЛИЧЕНО с 0.7 до 0.9 (или 0.7 для начала)
        hsv_v=0.7,       # Яркость (Value/Lightness) – УВЕЛИЧЕНО с 0.4 до 0.7
        
        # Аугментации геометрии: помогает бороться с однотипными ракурсами
        flipud=0.0,      # Вертикальное отражение – оставляем 0.0 (автомобили не летают)
        fliplr=0.5,      # Горизонтальное отражение – стандартное, но полезное
        shear=0.1,       # Сдвиг (Shear) – УВЕЛИЧЕНО с 0.0 до 0.1. Имитирует экстремальные ракурсы/искажения.
        perspective=0.0005, # Перспектива – небольшое искажение для робастности
        
        # Аугментация масштаба (помогает при разном расстоянии до объекта)
        scale=0.9,       # Диапазон масштабирования (0.9 означает от 10% уменьшения до 10% увеличения)
    )

if __name__ == '__main__':
    main()